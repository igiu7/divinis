"""
Turns a player animation .blend (made by build_dash.py, maybe edited by hand since) into a Java class of baked frames.

  blender -b tools/models/<anim>.blend --python tools/models/export_anim.py -- <Out.java>

Sampled every half tick over the scene's frame range, as offsets from standing (radians, model pixels, blocks):
- WHOLE: the whole body turning round PIVOT (rx, ry, rz, then the pivot's move x, y, z in model pixels);
- HEAD, BODY, RIGHT_ARM, LEFT_ARM, RIGHT_LEG, LEFT_LEG: the vanilla parts' rotations (rx, ry, rz);
- EYE: the first-person camera: forward, up (blocks, along the body's facing), pitch, roll (degrees).
"""
import math
import os
import sys

import bpy
from mathutils import Vector

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from mcmodel import m2b  # noqa: E402

STEP = 0.5
PARTS = ("head", "body", "right_arm", "left_arm", "right_leg", "left_leg")


def mc_rot(o):
    e = o.rotation_euler
    return (e[0], -e[2], e[1])  # Blender euler (XZY) -> model rotation (x, y, z)


def f(v):
    v = round(v, 4)
    return ("0.0" if v == 0 else str(v)) + "F"


def main():
    out = sys.argv[sys.argv.index("--") + 1:][0]
    cls = os.path.splitext(os.path.basename(out))[0]
    scene = bpy.context.scene
    ob = scene.objects
    whole, eye = ob["whole"], ob["eye"]
    pivot = tuple(whole["mc_pivot"])
    base = Vector(m2b(*pivot))

    def sample(t):
        scene.frame_set(int(t), subframe=t - int(t))
        bpy.context.view_layer.update()
        loc = whole.location - base
        row = {"WHOLE": list(mc_rot(whole)) + [loc.x, -loc.z, loc.y]}
        for p in PARTS:
            row[p.upper()] = list(mc_rot(ob[p]))
        e = eye.matrix_world.translation
        row["EYE"] = [-e.y, e.z, math.degrees(whole.rotation_euler[0] + ob["head"].rotation_euler[0]),
                      math.degrees(whole.rotation_euler[1])]
        return row

    n = int(round((scene.frame_end - scene.frame_start) / STEP)) + 1
    rows = [sample(scene.frame_start + i * STEP) for i in range(n)]
    eye0 = list(rows[0]["EYE"])
    for r in rows:  # the eye as a move from where it is standing, in blocks
        r["EYE"] = [(r["EYE"][0] - eye0[0]) / 16, (r["EYE"][1] - eye0[1]) / 16, r["EYE"][2], r["EYE"][3]]

    lines = [
        "package com.divinis.client;",
        "",
        "/**",
        f" * Generated by tools/models/export_anim.py from tools/models/{os.path.basename(bpy.data.filepath)} - do not edit by hand.",
        f" * {n} frames, one every {STEP} tick; each a row of offsets from standing (see export_anim.py).",
        " */",
        f"public final class {cls} {{",
        f"    private {cls}() {{}}",
        "",
        f"    public static final float STEP = {f(STEP)};",
        f"    public static final float LENGTH = {f((n - 1) * STEP)};",
        f"    public static final float[] PIVOT = {{{', '.join(f(v) for v in pivot)}}};",
    ]
    for ch in ["WHOLE"] + [p.upper() for p in PARTS] + ["EYE"]:
        lines.append("")
        lines.append(f"    public static final float[][] {ch} = {{")
        for r in rows:
            lines.append("            {" + ", ".join(f(v) for v in r[ch]) + "},")
        lines.append("    };")
    lines.append("}")
    with open(out, "w", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")
    print("exported", out, n, "frames")
    for i, r in enumerate(rows[::2]):
        print(i, "eye", [round(v, 2) for v in r["EYE"]])


main()
