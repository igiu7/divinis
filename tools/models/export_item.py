"""
Turns an item .blend (made by build_crystal.py or alike) into a Minecraft item model JSON.

  blender -b tools/models/<item>.blend --python tools/models/export_item.py -- <out.json>

Every mesh with the custom property "mc_el" is one element: its object location is the rotation origin, its
rotation (one axis, a multiple of 22.5 degrees) the element's rotation, its vertices the box; face UVs come from
"mc_uv" (north, south, east, west, up, down), the texture from the scene property "mc_texture", the display
transforms from "mc_display" (JSON; defaults otherwise). See itemmodel.py.
"""
import json
import math
import os
import sys

import bpy

FACES = ("north", "south", "east", "west", "up", "down")

DEFAULT_DISPLAY = {
    "gui": {"rotation": [30, 225, 0], "scale": [0.8, 0.8, 0.8]},
    "ground": {"translation": [0, 3, 0], "scale": [0.5, 0.5, 0.5]},
    "fixed": {"scale": [0.8, 0.8, 0.8]},
    "thirdperson_righthand": {"rotation": [75, 45, 0], "translation": [0, 2.5, 0], "scale": [0.5, 0.5, 0.5]},
    "firstperson_righthand": {"rotation": [0, 45, 0], "scale": [0.6, 0.6, 0.6]},
    "firstperson_lefthand": {"rotation": [0, 225, 0], "scale": [0.6, 0.6, 0.6]},
}


def b2j(x, y, z):
    return (8 - x, z, y + 8)


def r(v):
    v = round(v, 4)
    return int(v) if v == int(v) else v


def main():
    out = sys.argv[sys.argv.index("--") + 1:][0]
    scene = bpy.context.scene
    elements = []
    for ob in sorted((o for o in scene.objects if o.get("mc_el")), key=lambda o: o.name):
        origin = b2j(*ob.location)
        pts = [b2j(*(ob.location + v.co)) for v in ob.data.vertices]  # unrotated box around the origin
        frm = [r(min(p[i] for p in pts)) for i in range(3)]
        to = [r(max(p[i] for p in pts)) for i in range(3)]
        uv = list(ob["mc_uv"])
        el = {"from": frm, "to": to,
              "faces": {f: {"uv": [r(x) for x in uv[i * 4:i * 4 + 4]], "texture": "#0"} for i, f in enumerate(FACES)}}
        axis = ob.get("mc_axis", "")
        if axis:
            idx, sign = {"x": (0, -1), "y": (2, 1), "z": (1, 1)}[axis]
            angle = math.degrees(ob.rotation_euler[idx]) * sign
            el["rotation"] = {"angle": r(angle), "axis": axis, "origin": [r(x) for x in origin]}
        if ob.get("mc_glow", 0):
            el["neoforge_data"] = {"block_light": int(ob["mc_glow"]), "sky_light": int(ob["mc_glow"])}
        el["name"] = ob.name
        elements.append(el)
    model = {
        "credit": "Generated by tools/models/export_item.py from tools/models/" + os.path.basename(bpy.data.filepath),
        "parent": "minecraft:block/block",
        "textures": {"0": scene["mc_texture"], "particle": scene["mc_texture"]},
        "elements": elements,
        "display": json.loads(scene["mc_display"]) if "mc_display" in scene else DEFAULT_DISPLAY,
    }
    with open(out, "w", newline="\n") as fh:
        json.dump(model, fh, indent=2)
        fh.write("\n")
    print("exported", out, "elements:", len(elements))


main()
